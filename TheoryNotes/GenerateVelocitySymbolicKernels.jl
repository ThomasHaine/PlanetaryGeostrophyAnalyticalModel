# Generate portable Julia implementations of the B23 velocity kernels.
#
# Run this after `ComputeQuadratures.ipynb` updates `symexpr.jld2`. The
# generated source is used at runtime so production calculations do not depend
# on deserializing Symbolics internals.
using JLD2
using RuntimeGeneratedFunctions
using Symbolics

RuntimeGeneratedFunctions.init(@__MODULE__)

const EXPRESSION_FILE = joinpath(@__DIR__, "symexpr.jld2")
const OUTPUT_FILE = joinpath(@__DIR__, "VelocitySymbolicKernels.jl")

function generate_velocity_symbolic_kernels(kernels; output_file=OUTPUT_FILE)
    open(output_file, "w") do io
        println(io, "# Generated by GenerateVelocitySymbolicKernels.jl.")
        println(io, "# Do not edit manually; regenerate from ComputeQuadratures.ipynb.")
        println(io)

        for (name, expression, variables) in kernels
            generated = build_function(expression, variables...; expression=Val(true))
            body = deepcopy(generated.body)
            Base.remove_linenums!(body)

            println(io, "function $name(", join(string.(variables), ", "), ")")
            Base.show_unquoted(io, body, 0, 0)
            println(io, "\nend\n")
        end
    end

    println("Wrote $output_file")
    return output_file
end

function generate_velocity_symbolic_kernels(;
                                           expression_file=EXPRESSION_FILE,
                                           output_file=OUTPUT_FILE)
    isfile(expression_file) || throw(ArgumentError(
        "Missing $expression_file. Run ComputeQuadratures.ipynb first."
    ))

    @variables H z ξ ξp φ ψ κ ν β f H_y
    @load expression_file symbolics_Guvb symbolics_Guvb_xi symbolics_Guv_y_b symbolics_Guv_y_b_xi symbolics_inner_Gb_integral symbolics_inner_Gb2_integral

    kernels = [
        ("generated_guvb", symbolics_Guvb, (H, ψ, ξp, φ, z, κ, ν)),
        ("generated_guvb_xi", symbolics_Guvb_xi, (H, z, φ, ψ, κ, ν)),
        ("generated_guv_y_b", symbolics_Guv_y_b, (H, z, ξp, φ, ψ, κ, ν, β, f, H_y)),
        ("generated_guv_y_b_xi", symbolics_Guv_y_b_xi, (H, z, φ, ψ, κ, ν, β, f, H_y)),
        ("generated_inner_gb", symbolics_inner_Gb_integral, (H, ξ, ξp, ψ, κ)),
        ("generated_inner_gb_xi", symbolics_inner_Gb2_integral, (H, ξ, ψ, κ)),
    ]

    return generate_velocity_symbolic_kernels(kernels; output_file)
end

if abspath(PROGRAM_FILE) == @__FILE__
    generate_velocity_symbolic_kernels()
end
